# -- staleness (§2) -----------------------------------------------------------

def test_staleness():
    now = 1_800_000_000
    assert trust_shield.is_stale(now - 8 * 86400, 7, now)
    assert not trust_shield.is_stale(now - 6 * 86400, 7, now)
    assert not trust_shield.is_stale(now - 7 * 86400, 7, now)  # boundary: not >


# -- decision ladder (§3.3) ---------------------------------------------------

def test_policy_matches_fixture_expected_decisions():
    v = _v()
    provider = v["provider_pubkey"]
    ranks = {}
    for ev in v["rank_events"]:
        r = trust_shield.parse_rank_event(ev, provider)
        if r:
            ranks[r["subject"]] = r["rank"]
    pf = v["policy_fixture"]
    policy = trust_shield.TrustShieldPolicy(
        pf["threshold"], set(pf["follows"]), pf["self"]
    )
    for name, pk in v["targets"].items():
        assert policy.decide(pk, ranks.get(pk)) == pf["expected_decisions"][name], name
    # E1: self is never collapsed even at rank 0
    assert policy.decide(pf["self"], 0) == "normal"



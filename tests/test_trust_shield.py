"""trust-shield-v1 (NIP-85) golden-vector tests — spec t_d4ed8091.

Drives the synthetic-provider fixture (tests/fixtures/trust_shield_test_vectors.json,
generated by nip85_fixture.py with gnostr's own signer) through the full
acceptance floor: rank-event validation (R1-R5), provider aggregation (R6),
staleness, the §3.3 decision ladder, the §4 REQ byte-shape, kind-10040
discovery parsing, and the DB cache layer.

The real client is NOT importable under conftest's gi mocking (GObject
subclass), so the flag-off guarantee is pinned two ways: trust_settings
fallback behavior (no schema => defaults => flag off) plus a source-level
pin that the client's decide hook short-circuits before any state touch.
"""


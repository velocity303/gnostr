# -- kind-10040 discovery (§1.2) ----------------------------------------------

def test_discovery_entry_parsing():
    pk = "a" * 64
    ev = {
        "kind": 10040,
        "tags": [
            ["30382:rank", pk, "wss://rank.example/"],  # trailing / stripped
            ["30382:rank", "b" * 64, "ws://tapestry/relay"],  # no dot: dropped hint
            ["30382:rank", "not-hex"],  # bad provider: entry dropped
            ["other", "c" * 64],  # wrong tag name: ignored
            ["30382:rank", pk, "wss://dup.example"],  # dup provider, 2nd hint
        ],
    }
    entries = trust_shield.parse_discovery_entries(ev)
    assert (pk, "wss://rank.example") in entries
    assert ("b" * 64, None) in entries
    assert all(p != "not-hex" for p, _ in entries)
    assert ("b" * 64, "ws://tapestry/relay") not in entries


def test_relay_hint_validation():
    assert trust_shield.normalize_relay_hint("wss://relay.example/x") == "wss://relay.example/x"
    assert trust_shield.normalize_relay_hint("ws://relay.example") == "ws://relay.example"
    assert trust_shield.normalize_relay_hint("wss://relay.example/") == "wss://relay.example"
    assert trust_shield.normalize_relay_hint("ws://tapestry/relay") is None  # no dot
    assert trust_shield.normalize_relay_hint("https://relay.example") is None
    assert trust_shield.normalize_relay_hint("") is None
    assert trust_shield.normalize_relay_hint(None) is None


def test_rank_candidates_ranking_and_majority_hint():
    a, b = "a" * 64, "b" * 64
    entries = {
        "s1": [(a, "wss://one.example"), (b, "wss://two.example")],
        "s2": [(a, "wss://one.example"), (a, "wss://rare.example")],
        "s3": [(a, "wss://one.example")],
    }
    cands = trust_shield.rank_candidates(entries)
    assert cands[0]["provider"] == a  # listed by 3 subjects
    assert len(cands[0]["listed_by"]) == 3
    assert cands[0]["relay"] == "wss://one.example"  # most common hint
    assert cands[1]["provider"] == b



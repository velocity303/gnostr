def test_client_decide_short_circuits_when_inactive():
    """Source pin: trust_shield_decide returns NORMAL before touching any
    state while the flag/provider/relay is unset (flag-off = byte-for-byte
    pre-feature behavior; the UI gates on this single hook)."""
    src = os.path.join(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
        "src", "gnostr", "client.py",
    )
    with open(src) as f:
        text = f.read()
    i = text.index("def trust_shield_decide")
    body = text[i : i + 900]
    assert "if self._trust_dead or not self._trust_active():" in body
    guard = body.index("if self._trust_dead or not self._trust_active():")
    first_if = body.index("if ")
    assert guard == first_if  # guard is the FIRST statement after docstring
    # _trust_active requires flag AND provider AND relay
    j = text.index("def _trust_active")
    active_body = text[j : j + 300]
    for key in ("trust-shield\"", "trust-shield-provider\"", "trust-shield-relay\""):
        assert key in active_body


# -- DB cache layer (§5.2) ----------------------------------------------------

def test_trust_rank_db_roundtrip_and_purge(tmp_path, monkeypatch):
    _patch_glib_dirs(monkeypatch, tmp_path)
    db = Database()
    prov, other = "a" * 64, "b" * 64
    subj = "c" * 64
    assert db.get_trust_rank(prov, subj) is None
    db.upsert_trust_rank(prov, subj, 42, 12345)
    row = db.get_trust_rank(prov, subj)
    assert row["rank"] == 42 and row["rank_updated"] == 12345
    # upsert replaces (same provider+subject)
    db.upsert_trust_rank(prov, subj, 55, 12346)
    assert db.get_trust_rank(prov, subj)["rank"] == 55
    assert db.trust_rank_count(prov) == 1
    db.upsert_trust_rank(other, subj, 1, 12347)
    assert db.trust_rank_count(other) == 1
    assert db.trust_last_fetch(prov) >= 12346 or db.trust_last_fetch(prov) > 0
    db.purge_other_trust_ranks(prov)
    assert db.trust_rank_count(other) == 0
    assert db.trust_rank_count(prov) == 1


def test_fixture_ranks_into_db_then_policy(tmp_path, monkeypatch):
    """End-to-end synthetic-provider acceptance: fixture rank events ->
    parse -> DB cache -> select_rank -> policy decisions == spec expected."""
    _patch_glib_dirs(monkeypatch, tmp_path)
    v = _v()
    provider = v["provider_pubkey"]
    db = Database()
    for ev in v["rank_events"]:
        r = trust_shield.parse_rank_event(ev, provider)
        if r:
            db.upsert_trust_rank(provider, r["subject"], r["rank"], r["created_at"])
    pf = v["policy_fixture"]
    policy = trust_shield.TrustShieldPolicy(
        pf["threshold"], set(pf["follows"]), pf["self"]
    )
    for name, pk in v["targets"].items():
        row = db.get_trust_rank(provider, pk)
        rank = trust_shield.select_rank([row]) if row else None
        assert policy.decide(pk, rank) == pf["expected_decisions"][name], name
    assert db.trust_rank_count(provider) == 6  # malformed event never stored

def _v():
    with open(FIXTURE) as f:
        return json.load(f)


def _patch_glib_dirs(monkeypatch, tmp_path):
    monkeypatch.setattr(GLib, "get_user_data_dir", lambda: str(tmp_path / "data"))


# -- rank-event validation (R1-R5) ------------------------------------------

def test_all_valid_rank_events_parse():
    v = _v()
    provider = v["provider_pubkey"]
    parsed = {}
    for ev in v["rank_events"]:
        r = trust_shield.parse_rank_event(ev, provider)
        if r is None:
            continue
        parsed[r["subject"]] = r
    # 6 valid ranks; the rank=400 event (target6) must be dropped (R4).
    assert len(parsed) == 6
    assert parsed[v["targets"]["target1"]]["rank"] == 90
    assert parsed[v["targets"]["target3"]]["rank"] == 25  # boundary kept
    assert parsed[v["targets"]["target4"]]["rank"] == 24
    assert v["targets"]["target6"] not in parsed  # out-of-range dropped
    for r in parsed.values():
        assert r["created_at"] == 1763500001
        assert len(r["event_id"]) == 64


def test_rank_event_rejects_wrong_signer_and_kind():
    v = _v()
    ev = dict(v["rank_events"][0])
    # R1: signer != configured provider
    assert trust_shield.parse_rank_event(ev, "0" * 64) is None
    # R1: wrong kind
    ev2 = dict(v["rank_events"][0])
    ev2["kind"] = 1
    assert trust_shield.parse_rank_event(ev2, v["provider_pubkey"]) is None
    # R2: tampered content breaks id/sig recompute
    ev3 = dict(v["rank_events"][0])
    ev3["content"] = "tampered"
    assert trust_shield.parse_rank_event(ev3, v["provider_pubkey"]) is None


def test_rank_event_rejects_malformed_tags():
    v = _v()
    base = v["rank_events"][0]
    for bad_tags in (
        [],  # no d, no rank
        [["d", "zz"], ["rank", "5"]],  # d not hex
        [["d", base["tags"][0][1]]],  # no rank tag
        [["d", base["tags"][0][1]], ["rank", "5"], ["rank", "6"]],  # two ranks
        [["d", base["tags"][0][1]], ["rank", "-1"]],  # below 0
    ):
        ev = dict(base)
        ev["tags"] = bad_tags
        assert trust_shield.parse_rank_event(ev, v["provider_pubkey"]) is None


